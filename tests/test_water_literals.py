NUMBER = r"(?<![\w.\[])[-+]?(?:\d+\.\d*|\.\d+)(?:[eE][-+]?\d+)?f?(?![\w.\]])"


def bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def lines(kind):
    """The arguments of the table's lines of one kind, in the file's order."""
    return [tuple(a.strip() for a in m.group(1).split(",")) for m in re.finditer(r"^FABLE2_WATER_%s\(([^)]*)\)$" % kind, INC, re.M)]


class Table(unittest.TestCase):
    def test_the_shaders(self):
        self.assertEqual(lines("SHADERS"), [("0x%sull" % S["vs"], "0x%sull" % S["ps"], "0x%sull" % S["ps_opaque"])])

    def test_the_registers_their_order_and_what_is_read(self):
        vertex = lines("VS_REGISTER")
        self.assertEqual([int(reg) for reg, _ in vertex], list(S["reg"]))
        self.assertEqual([int(reg) for reg, _ in vertex], sorted(S["reg"]))               # ascending: the record's order
        for reg, mask in vertex:
            self.assertEqual(int(mask, 16), sum(1 << k for k in S["vs_read"][int(reg)]), reg)
        pixel = lines("PS_REGISTER")
        self.assertEqual([int(reg) for reg, _, _ in pixel], list(S["ps_reg"]))
        self.assertEqual(list(S["ps_reg"]), sorted(S["ps_reg"]))
        for reg, mask, kind in pixel:
            self.assertEqual(int(mask, 16), sum(1 << k for k in S["ps_read"][int(reg)]), reg)
            self.assertEqual(int(kind), gen.KIND[int(reg)], reg)
        # what a formula does not read is the complement, component for component (water_check.UNREAD)
        for reg, mask, _ in pixel:
            self.assertEqual(tuple(k for k in range(4) if not int(mask, 16) >> k & 1), water_check.UNREAD[int(reg)], reg)
        self.assertEqual(len(pixel) * 4 - sum(bin(int(mask, 16)).count("1") for _, mask, _ in pixel), 46)

    def test_the_registers_the_bools_gate(self):
        for bool_, registers in S["ps_read_under"].items():
            for reg in registers:
                self.assertIn(reg, S["ps_reg"], (bool_, reg))
        self.assertEqual(lines("BOOL"), [("b136", "0x%08Xu" % S["b136"]), ("b137", "0x%08Xu" % S["b137"])])
        self.assertEqual((S["b136"], S["b137"]), (1 << (136 & 31), 1 << (137 & 31)))       # bit N & 31 of the word b128..b159
        self.assertEqual(lf.water_bools(0x00000110), (136,))                               # every captured row's word
        self.assertEqual(lf.water_bools(0x00000310), (136, 137))

    def test_the_literals_by_bits_and_by_name(self):
        table = {int(reg): tuple(int(b[:-1], 16) for b in rest) for reg, *rest in lines("LITERAL")}
        self.assertEqual(table, {reg: tuple(bits(v) for v in values) for reg, values in S["ps_lit"].items()})
        names = lf.water_literals()
        self.assertEqual(names, {"zero": 0.0, "two": 2.0, "half": 0.5, "minus_one": -1.0, "one": 1.0, "minus_two": -2.0})
        for name, (reg, comp) in S["ps_lit_at"].items():
            self.assertEqual(bits(names[name]), table[reg][comp], name)

    def test_the_fetch_slots(self):
        slots = S["ps_slots"]
        self.assertEqual(lines("FETCH_SLOT"), [("0", str(slots["mask"])), ("1", str(slots["normal"])), ("2", str(slots["reflection"])),
                                               ("3", str(slots["near"]))])

    def test_the_three_zero_product_registers_are_held_above_0(self):
        """Ledger ruling 34."""
        kinds = {int(reg): int(kind) for reg, _, kind in lines("PS_REGISTER")}
        self.assertEqual(sorted(reg for reg, kind in kinds.items() if kind == 3), [128, 136, 138])
        self.assertGreater(gen.BOUND[3][0], 0.0)


class Pins(unittest.TestCase):
    def test_the_pins_registers_are_the_tables_in_its_order(self):
        self.assertEqual(water_pins.VS_REG, (0, 1, 2, 3) + tuple(int(reg) for reg, _ in lines("VS_REGISTER")))
        self.assertEqual(water_pins.PS_REG, tuple(int(reg) for reg, _, _ in lines("PS_REGISTER")))
        for row in water_pins.CAPTURED_ROWS:
            self.assertEqual((len(row[4]), len(row[5])), (8, 24))
            self.assertTrue(all(len(reg) == 4 for reg in row[4] + row[5]))

    def test_a_pixel_line_has_the_registers_and_the_outputs(self):
        pixel = [line for line in water_pins.lines() if line.count("{") > 30]
        self.assertEqual(len(pixel), len(water_pins.CAPTURED_PIXELS) + len(water_pins.MADE_PIXELS))
        for line in pixel:
            groups = re.findall(r"\{((?:0x[0-9A-F]{8}u(?:, )?)+)\}", line)
            self.assertEqual(sum(1 for g in groups if g.count("0x") == 4), 24 + 1, line[:80])       # the registers, and o1

    def test_the_two_thresholds_are_two_numbers(self):
        """c141.w decides shaded against colour 0, the state's alpha reference drawn against not: one unit in the
        last place apart in every captured row (water_check.py states)."""
        self.assertEqual(water_pins.CAPTURED_C141[3], 0x3D70F0F1)
        self.assertEqual(water_pins.REFERENCE, 0x3D70F0F2)
        self.assertIn(141, S["ps_reg"])
        self.assertIn(3, S["ps_read"][141])
        self.assertNotIn("210E", INC)                                 # the reference is a state word of the draw record, not a register of the table

    def test_the_captured_registers_are_inside_the_tables_bounds(self):
        e = gen.entry()
        for index in range(len(water_pins.CAPTURED_ROWS)):
            vertex, pixel, _ = water_pins.row_registers(index)
            registers = {("vs", reg): vertex[reg] for reg in S["reg"]}
            registers.update({("ps", reg): pixel[reg] for reg in S["ps_reg"]})
            self.assertEqual(gen.outside(e, registers), [], index)


def _source(*parts):
    return (ROOT / "src" / "native").joinpath(*parts).read_text(encoding="utf-8").replace("\r\n", "\n")


def _function(text, head):
    """The text of the C++ function whose definition starts with `head`, to its closing brace at column 0."""
    at = text.index(head)
    return text[at:text.index("\n}\n", at) + 3]


class Record(unittest.TestCase):
    """The C++ side of plan Task 9: water_record.h against the table and the reference, and where the capture
    reaches it (source text: capture.cpp has no unit test)."""
    HEADER = _source("capture", "water_record.h")
    CAPTURE = _source("capture", "capture.cpp")

    def test_the_enumerators_are_the_tables_registers_in_its_order(self):
        vertex = re.search(r"enum : uint32_t \{ (kWatV[^}]*) \};", self.HEADER).group(1)
        pixel = re.search(r"enum : uint32_t \{ (kWatP[^}]*?) \};", self.HEADER, re.S).group(1)
        self.assertEqual([int(n[5:]) for n in re.findall(r"kWatV\d+", vertex)], list(S["reg"]))
        self.assertEqual([int(n[5:]) for n in re.findall(r"kWatP\d+", pixel)], list(S["ps_reg"]))
        self.assertIn("inline constexpr uint32_t kWaterVsRegisters = %d, kWaterPsRegisters = %d;" % (len(S["reg"]), len(S["ps_reg"])), self.HEADER)
        self.assertIn("enum : uint32_t { kWatMask, kWatNormal, kWatPicture, kWatNear };", self.HEADER)
        self.assertIn("inline constexpr uint32_t kMaxWaterRecords = 64;", self.HEADER)

    def test_the_record_is_584_bytes_of_what_the_spec_carries(self):
        """16 + 16 + 4 * 16 + 24 * 16 + 4 * 24 + 8: the hashes; place, kind, bool word, stride; the vertex registers;
        the pixel registers; four fetch constants; the two fog tables' bases."""
        self.assertEqual(16 + 16 + 16 * len(S["reg"]) + 16 * len(S["ps_reg"]) + 4 * 24 + 8, 584)
        self.assertIn("static_assert(sizeof(WaterRecord) == 584,", self.HEADER)
        self.assertIn("static_assert(sizeof(DrawRecord) == 616,", _source("capture", "draw_record.h"))

    def test_the_reasons_are_the_specs_in_its_order(self):
        names = re.search(r"static constexpr const char\* kNames\[\] = \{([^}]*)\};", _function(self.HEADER, "inline const char* WaterReasonName(")).group(1)
        self.assertEqual(re.findall(r'"([^"]+)"', names), ["none", "unread", "shader", "literal", "fetch-list", "register", "scale", "state",
                                                          "fetch", "shadow-term", "fog", "over-limit"])
        self.assertIn('inline constexpr const char* kWaterRecordReason = "water-record";', self.HEADER)

    def test_the_bounds_by_kind_are_the_generators(self):
        number = {"kWaterPlaceMax": gen.BOUND[0][1], "kWaterMatrixMax": gen.BOUND[1][1], "kWaterFactorMax": gen.BOUND[2][1]}
        for name, want in number.items():
            got = re.search(r"\b%s = ([-+0-9.eE]+)f" % name, self.HEADER).group(1)
            self.assertEqual(float(got), want, name)
        self.assertIn("inline constexpr float kWaterFactorMin = 1.0f / 65536.0f;", self.HEADER)
        self.assertEqual(gen.BOUND[3], (1.0 / 65536.0, 65536.0))
        self.assertIn("inline constexpr uint32_t kWaterVsKind = %d;" % gen.VS_KIND, self.HEADER)
        body = _function(self.HEADER, "inline bool Bounded(")
        self.assertIn("case 0: return std::fabs(v) <= kWaterPlaceMax;", body)
        self.assertIn("case 2: return std::fabs(v) <= kWaterFactorMax;", body)
        self.assertIn("default: return v >= kWaterFactorMin && v <= kWaterFactorMax;", body)

    def test_the_registers_under_a_bool_are_judged_under_it_alone(self):
        body = _function(self.HEADER, "constexpr bool PsRegisterRead(")
        under136 = sorted(int(n) for n in re.findall(r"index == kWatP(\d+)", body.split("return (pbool & kWaterB136)")[0]))
        self.assertEqual(under136, sorted(S["ps_read_under"][136]))
        self.assertEqual(S["ps_read_under"][137], (139,))
        self.assertIn("return index != kWatP139;", body)                    # read under b137 alone, which gives no record

    def test_the_named_components_are_read_components(self):
        """Every register component CheckWaterDraw names is one a formula reads (a bound on an unread component
        would refuse a draw for garbage nobody uses)."""
        body = _function(self.HEADER, "inline WaterReason CheckWaterDraw(") + _function(self.HEADER, "inline bool WaterRegistersBounded(")
        named = {(int(reg), int(k)) for reg, k in re.findall(r"\bps\[kWatP(\d+)\]\[(\d)\]", body)}
        self.assertEqual(named, {(128, 0), (131, 0), (136, 0), (141, 3), (0, 2), (0, 3), (20, 3)})
        for reg, k in named:
            self.assertIn(k, S["ps_read"][reg], (reg, k))
        self.assertIn("const float* c31 = ps[kWatP31];", body)
        self.assertEqual(S["ps_read"][31], (0, 1))
        fog = _function(self.HEADER, "inline bool WaterFogMatches(")
        self.assertEqual(sorted({int(reg) for reg in re.findall(r"kWatP(\d+)", fog)}), [28, 66, 67, 68])
        self.assertIn("const float range[3] = {r.ps[kWatP67][0], r.ps[kWatP67][2], r.ps[kWatP67][3]};", fog)     # not c67.y
        self.assertEqual(S["ps_read"][67], (0, 2, 3))

    def test_with_the_switch_off_the_capture_reaches_nothing_but_one_load_and_one_compare(self):
        c = self.CAPTURE
        # one call of the observer, on the no-albedo branch, behind the frame's latched word
        calls = re.findall(r"^.*\bObserveWaterDraw\(.*$", c, re.M)
        self.assertEqual(len(calls), 3, calls)                               # the forward declaration, the call, the definition
        fill = _function(c, "void FillMaterial(uint32_t device, DrawShaders& shaders, DrawInputs& in) {")
        self.assertIn("  if (albedo->slot < 0) {\n    m.status = MaterialStatus::kNoAlbedo;\n", fill)
        branch = fill[fill.index("if (albedo->slot < 0) {"):fill.index("ResolveAlbedo(device, shaders.dev")]
        self.assertIn("if (g_water_frame.load(std::memory_order_relaxed)) ObserveWaterDraw(device, shaders, ps_obj, *ps);", branch)
        self.assertEqual(fill.count("g_water_frame"), 1)
        self.assertEqual(fill.count("ObserveWaterDraw"), 1)
        # one record made, in RecordDraw, behind the draw's own material status and then the thread's byte
        record = _function(c, "uint32_t RecordDraw(uint32_t id, const LastArgs& a, uint32_t device) {")
        self.assertEqual(c.count("MakeWaterRecord("), 1)
        self.assertIn("if (in.material.status == MaterialStatus::kNoAlbedo && t_water_kind != WaterKind::kNone) {\n"
                      "    water_kind = t_water_kind;\n    t_water_kind = WaterKind::kNone;\n"
                      "    water_record = MakeWaterRecord(t_water_draw, in.state_words, kWaterSceneWidth, kWaterSceneHeight, &water_why);\n  }", record)
        self.assertEqual(record.count("t_water_kind"), 3)
        self.assertEqual(record.count("g_builder.AddWater("), 1)
        self.assertIn("  if (water_kind != WaterKind::kNone) {\n    g_builder.WaterSeen(water_kind);", record)
        # the thread's byte is written by the observer and taken by RecordDraw, nowhere else
        writes = re.findall(r"^\s*t_water_kind = [^;]*;", c, re.M)
        self.assertEqual(sorted(w.strip() for w in writes), ["t_water_kind = WaterKind::kNone;", "t_water_kind = kind;"])
        # everything of the observer lies behind the pixel shader's hash
        observe = _function(c, "void ObserveWaterDraw(uint32_t device, const DrawShaders& shaders, uint32_t ps_obj, const PsInfo& ps) {")
        head = observe[:observe.index("t_water_kind = kind;")]
        self.assertIn("if (kind == WaterKind::kNone) return;", head)
        self.assertNotIn("Read", head.split("{", 1)[1])

    def test_the_frame_row_is_written_from_the_scenes_stored_records(self):
        """Not from a second read at the draw (sub-project 11's gap, sub-project 12's review of Tasks 8 and 9)."""
        body = _function(self.CAPTURE, "void AppendFrameWater(std::string& row, const render::FrameScene& sc) {")
        self.assertIn("const std::vector<WaterRecord>& records = whole ? sc.water : sc.water_evidence;", body)
        for word in ("t_water_draw", "t_water_kind", "ReadVirtual", "ReadPixelConstant", "g_builder"):
            self.assertNotIn(word, body, word)
        self.assertIn("AppendFrameWater(row, *done->scene);", self.CAPTURE)

    def test_the_bool_word_is_followed_for_the_water_and_begins_anew_only_from_nothing(self):
        c = self.CAPTURE
        self.assertIn("inline constexpr uint8_t kFollowWater = 4;", c)
        self.assertIn("inline constexpr uint8_t kFollowWord = kFollowImpostors | kFollowWater;", c)
        self.assertEqual(c.count("g_impostor_epoch.fetch_add("), 1)
        self.assertIn("if (followed_now && !followed_before) g_impostor_epoch.fetch_add(1, std::memory_order_relaxed);", c)
        self.assertIn("d.pbool_known = read && ImpostorBoolWord(vc, ps_obj, &d.pbool);", c)
        # the three places that follow the word follow it for either reader
        self.assertEqual(len(re.findall(r"& kFollowWord\b", c)), 3)
        self.assertEqual(len(re.findall(r"& kFollowImpostors\b", c)), 0)

    def test_the_switch_is_off_by_default(self):
        render = _source("fable2_native_render.cpp")
        self.assertIn('REXCVAR_DEFINE_STRING(fable2_native_water, "off", "Fable2",', render)
        self.assertIn("capture::SetWaterWanted(wanted && CurrentWater());", render)
        self.assertIn('REXLOG_INFO("[native] water: {} (fable2_native_water)", CurrentWater() ? "on" : "off");', render)


class Text(unittest.TestCase):
    """The stand-in text today, the header's own from plan Task 12 on (no skip: the fixture is always held)."""

    def texts(self):
        out = [("the fixture", hlsl.FIXTURE)]
        if hlsl.HAS_TEXT:
            out.append(("the header", hlsl.HEADER))
        return out

    def test_a_number_in_the_text_is_a_literal_of_the_shader(self):
        allowed = {abs(v) for v in lf.water_literals().values()}
        for name, text in self.texts():
            for begin, end, _ in (wind_hlsl.WATER_VERTEX, wind_hlsl.WATER_PIXEL):
                code = "\n".join(line.split("//")[0] for line in wind_hlsl.region(text, begin, end).split("\n"))
                for number in re.findall(NUMBER, code):
                    self.assertIn(abs(float(number.rstrip("f"))), allowed, (name, number))

    def test_the_functions_take_the_registers_the_reference_reads(self):
        """A register named in a function's arguments (cNNN, or cNNNx for a component) is one of the table's, and
        every register a formula of these functions reads is named by one of them."""
        for name, text in self.texts():
            named = set()
            for begin, end, _ in (wind_hlsl.WATER_VERTEX, wind_hlsl.WATER_PIXEL):
                for args in re.findall(r"^float\d? \w+\(([^)]*)\) \{", wind_hlsl.region(text, begin, end), re.M):
                    named |= {int(n) for n in re.findall(r"\bc(\d+)x?\b", args)}
            self.assertTrue(named <= set(S["reg"]) | set(S["ps_reg"]), (name, sorted(named)))
            # the fog's registers, the exposure, the eye (passed as a place) and the shadow factor are the main's
            mains = {19, 20, 28, 66, 67, 68, 139}
            self.assertEqual(named, (set(S["reg"]) | set(S["ps_reg"])) - mains, name)


