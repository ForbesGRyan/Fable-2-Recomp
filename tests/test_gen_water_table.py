from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "xdk_sigmatch"))

import gen_water_table as gen  # noqa: E402
import light_formulas as lf  # noqa: E402

INC = ROOT / "src" / "native" / "capture" / "water_table.inc"


def bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def made():
    """A small entry: two vertex registers, three pixel registers, one literal register, two bools, two slots."""
    return {"vs": "00000000000000AB", "ps": "00000000000000CD", "ps_opaque": "00000000000000EF",
            "reg": (116, 115), "vs_read": {115: (0, 1), 116: (0,)},
            "ps_reg": (141, 19, 20), "ps_read": {19: (0, 1, 2), 20: (3,), 141: (0, 1, 3)},
            "kind": {19: 0, 20: 3, 141: 2},
            "ps_lit": {255: (0.5, -1.0, 1.0, -2.0)},
            "bools": {"b136": 0x100, "b137": 0x200},
            "slots": (1, 13)}


class Generate(unittest.TestCase):
    def test_every_line_of_a_made_entry(self):
        text = gen.generate(made())
        lines = text.splitlines()
        self.assertTrue(lines[0].startswith("// Generated by tools/xdk_sigmatch/gen_water_table.py"))
        body = [line for line in lines if not line.startswith("//")]
        self.assertEqual(body[0], "FABLE2_WATER_SHADERS(0x00000000000000ABull, 0x00000000000000CDull, 0x00000000000000EFull)")
        self.assertEqual([line for line in body if line.startswith("FABLE2_WATER_VS_REGISTER")],
                         ["FABLE2_WATER_VS_REGISTER(115, 0x3)", "FABLE2_WATER_VS_REGISTER(116, 0x1)"])        # ascending
        self.assertEqual([line for line in body if line.startswith("FABLE2_WATER_PS_REGISTER")],
                         ["FABLE2_WATER_PS_REGISTER(19, 0x7, 0)", "FABLE2_WATER_PS_REGISTER(20, 0x8, 3)",
                          "FABLE2_WATER_PS_REGISTER(141, 0xB, 2)"])
        self.assertEqual([line for line in body if line.startswith("FABLE2_WATER_LITERAL")],
                         ["FABLE2_WATER_LITERAL(255, 0x3F000000u, 0xBF800000u, 0x3F800000u, 0xC0000000u)"])
        self.assertEqual([line for line in body if line.startswith("FABLE2_WATER_BOOL")],
                         ["FABLE2_WATER_BOOL(b136, 0x00000100u)", "FABLE2_WATER_BOOL(b137, 0x00000200u)"])
        self.assertEqual([line for line in body if line.startswith("FABLE2_WATER_FETCH_SLOT")],
                         ["FABLE2_WATER_FETCH_SLOT(0, 1)", "FABLE2_WATER_FETCH_SLOT(1, 13)"])
        kinds = [re.match(r"FABLE2_WATER_([A-Z_]+)\(", line).group(1) for line in body]
        self.assertEqual(sorted(set(kinds)), sorted(["SHADERS", "VS_REGISTER", "PS_REGISTER", "LITERAL", "BOOL", "FETCH_SLOT"]))
        self.assertEqual(len(body), 1 + 2 + 3 + 1 + 2 + 2)          # every line once
        self.assertTrue(text.endswith("\n") and "\r" not in text)

    def refused(self, change, word):
        entry = copy.deepcopy(made())
        change(entry)
        with self.assertRaises(ValueError) as e:
            gen.generate(entry)
        self.assertIn(word, str(e.exception))

    def test_what_is_refused(self):
        self.refused(lambda e: e.__setitem__("reg", (115, 116, 115)), "twice")
        self.refused(lambda e: e.__setitem__("ps_reg", (19, 20, 141, 19)), "twice")
        self.refused(lambda e: e["ps_read"].__setitem__(20, ()), "read mask of 0")       # a bound is asked for (its kind)
        self.refused(lambda e: e["vs_read"].__setitem__(116, ()), "read mask of 0")
        self.refused(lambda e: e["ps_read"].pop(141), "no read components")
        self.refused(lambda e: e["ps_read"].__setitem__(20, (4,)), "component")
        self.refused(lambda e: e["bools"].__setitem__("b137", 0x300), "one bit")
        self.refused(lambda e: e["bools"].__setitem__("b137", 0x100), "the same bit")
        self.refused(lambda e: e["bools"].__setitem__("9lives", 0x400), "name")
        self.refused(lambda e: e["kind"].__setitem__(20, 4), "kind")
        self.refused(lambda e: e["kind"].pop(19), "kind")
        self.refused(lambda e: e.__setitem__("reg", (115, 250)), "below 248")
        self.refused(lambda e: e.__setitem__("vs", "12"), "16 hex digits")
        self.refused(lambda e: e.__setitem__("ps_opaque", "0" * 16), "zero")
        self.refused(lambda e: e.__setitem__("ps_opaque", "00000000000000CD"), "the same hash")
        self.refused(lambda e: e.__setitem__("ps_lit", {255: (0.0, 1.0)}), "four values")
        self.refused(lambda e: e.__setitem__("ps_lit", {19: (0.0, 1.0, 2.0, 3.0)}), "literal register")
        self.refused(lambda e: e.__setitem__("slots", (1, 1)), "twice")
        self.refused(lambda e: e.__setitem__("slots", (1, 32)), "slot")

    def test_the_committed_file_is_the_generators(self):
        self.assertEqual(INC.read_text(encoding="utf-8").replace("\r\n", "\n"), gen.generate(gen.entry()))
        self.assertEqual(gen.main(["--check"]), 0)

    def test_the_real_entry_is_the_formulas_table(self):
        e, s = gen.entry(), lf.WATER_SHADER
        self.assertEqual((e["vs"], e["ps"], e["ps_opaque"]), (s["vs"], s["ps"], s["ps_opaque"]))
        self.assertEqual((tuple(e["reg"]), tuple(e["ps_reg"])), (tuple(s["reg"]), tuple(s["ps_reg"])))
        self.assertEqual(e["vs_read"], {reg: s["vs_read"][reg] for reg in s["reg"]})
        self.assertEqual(e["ps_read"], s["ps_read"])
        self.assertEqual(e["ps_lit"], s["ps_lit"])
        self.assertEqual(e["bools"], {"b136": s["b136"], "b137": s["b137"]})
        self.assertEqual(tuple(e["slots"]), (s["ps_slots"]["mask"], s["ps_slots"]["normal"], s["ps_slots"]["reflection"], s["ps_slots"]["near"]))
        self.assertEqual(set(e["kind"]), set(s["ps_reg"]))
        text = gen.generate(e)
        self.assertEqual(text.count("FABLE2_WATER_VS_REGISTER("), 4)
        self.assertEqual(text.count("FABLE2_WATER_PS_REGISTER("), 24)
        self.assertIn("FABLE2_WATER_PS_REGISTER(141, 0xB, 2)", text)      # c141.xyw: z is not read
        self.assertIn("FABLE2_WATER_PS_REGISTER(19, 0x7, 0)", text)       # the eye: a place
        self.assertIn("FABLE2_WATER_PS_REGISTER(67, 0xD, 0)", text)       # the fog's start is a distance: the widest kind of its components
        # (ledger ruling 34) the three registers at the console's zero-product points are held ABOVE 0
        for reg in (128, 136, 138):
            self.assertIn("FABLE2_WATER_PS_REGISTER(%d, 0x1, 3)" % reg, text)
        self.assertEqual(sorted(reg for reg, kind in e["kind"].items() if kind == 3), [128, 136, 138])
        self.assertEqual(gen.BOUND[3], (1.0 / 65536.0, 65536.0))
        self.assertIn("FABLE2_WATER_BOOL(b136, 0x00000100u)", text)
        self.assertIn("FABLE2_WATER_BOOL(b137, 0x00000200u)", text)
        # 50 components read by the pixel formulas, 8 by the vertex formula beyond the rows
        masks = [int(m, 16) for m in re.findall(r"FABLE2_WATER_PS_REGISTER\(\d+, (0x[0-9A-F]), \d\)", text)]
        self.assertEqual(sum(bin(m).count("1") for m in masks), 50)
        masks = [int(m, 16) for m in re.findall(r"FABLE2_WATER_VS_REGISTER\(\d+, (0x[0-9A-F])\)", text)]
        self.assertEqual(sum(bin(m).count("1") for m in masks), 8)

    def test_the_sanity_bounds_refuse_garbage_on_read_components_alone(self):
        """Sub-project 12's lesson (its ledger rulings 34 and 54): a bound by the component's kind, fitted to no
        capture, on the components a formula reads and on no other."""
        self.assertEqual((gen.PLACE, gen.MATRIX, gen.SCALE), (1e6, 1e7, 65536.0))
        e = gen.entry()
        far = gen.far_region()
        self.assertEqual(gen.outside(e, far), [])
        self.assertEqual(far[("ps", 19)][:3], [5000.0, -5000.0, 300.0])
        self.assertEqual(far[("ps", 67)][0], 200.0)
        for (bank, reg), comps in gen.read_components(e).items():
            for i in range(4):
                for bad in (float("nan"), float("inf"), float("-inf"), 1e20, -1e20, 3.0e38):
                    changed = {k: list(v) for k, v in far.items()}
                    changed[(bank, reg)][i] = bad
                    self.assertEqual(gen.outside(e, changed), [((bank, reg), i)] if i in comps else [], (bank, reg, i, bad))
        # Ledger ruling 42 (the review of Tasks 4 to 15, I3): another region's record, with what the spec's named
        # bounds of before refused and the formula takes, is inside every bound; the C++ rule names none of the
        # three registers beyond the table's kinds.
        other = gen.other_region()
        self.assertEqual(gen.outside(e, other), [])
        self.assertEqual((other[("ps", 131)][0], other[("ps", 128)][0], other[("ps", 136)][0]), (-0.5, 200.0, 90.0))
        self.assertEqual((e["kind"][131], e["kind"][128], e["kind"][136]), (2, 3, 3))
        header = (ROOT / "src" / "native" / "capture" / "water_record.h").read_text(encoding="utf-8")
        self.assertNotIn("kWaterShareMax", header)
        self.assertNotIn("ps[kWatP131][0] >= 0.0f", header)
        # the three zero-product registers: 0, a negative and a denormal are refused, the floor itself is not
        for reg in (128, 136, 138):
            for value, refused in ((0.0, True), (-0.0, True), (-1.0, True), (1e-30, True), (1.0 / 65536.0, False), (65536.0, False)):
                changed = {k: list(v) for k, v in far.items()}
                changed[("ps", reg)][0] = value
                self.assertEqual(gen.outside(e, changed), [(("ps", reg), 0)] if refused else [], (reg, value))
        # and nothing else of the table is held away from 0
        for key in far:
            if key[1] not in (128, 136, 138):
                changed = {k: list(v) for k, v in far.items()}
                changed[key] = [0.0, 0.0, 0.0, 0.0]
                self.assertEqual(gen.outside(e, changed), [], key)
        # every captured value of a read component is at least eighty times inside its bound
        for key, span in gen.CAPTURED.items():
            for i, pair in enumerate(span):
                if pair is None:
                    self.assertNotIn(i, gen.read_components(e)[key], (key, i))
                    continue
                self.assertIn(i, gen.read_components(e)[key], (key, i))
                reach = gen.reach(e, key)
                self.assertTrue(math.isfinite(pair[0]) and math.isfinite(pair[1]))
                self.assertGreaterEqual(reach, 80.0 * max(abs(pair[0]), abs(pair[1])), (key, i))

    def test_check_names_a_stale_file(self):
        with tempfile.TemporaryDirectory() as folder:
            out = Path(folder) / "water_table.inc"
            self.assertEqual(gen.main(["--out", str(out)]), 0)
            self.assertEqual(gen.main(["--check", "--out", str(out)]), 0)
            out.write_text(out.read_text().replace("FABLE2_WATER_FETCH_SLOT(2, 13)", "FABLE2_WATER_FETCH_SLOT(2, 12)"), newline="\n")
            self.assertEqual(gen.main(["--check", "--out", str(out)]), 1)


