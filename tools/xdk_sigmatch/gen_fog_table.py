"""light_formulas.FOG_SHADERS -> src/native/capture/fog_shader_table.inc.

  FABLE2_FOG_SHADER(ps, world, alpha)

One line per pixel shader that has the game's fog block (docs/native-renderer/lighting-formulas.md, "Fog and
sky"; every one is checked against its microcode by fog_check.py). `ps`: the shader's hash. `world`: the
interpolator that is the pixel's world position (interpolator N is register rN of the pixel shader).
`alpha`: 0 the plain form, 1 the blended form, whose in-scatter term is multiplied by the pixel's alpha.

The capture reads a frame's fog block at the first main-scene colour draw of one of these shaders
(src/native/capture/fog_block.h, FindFogShader): there the six registers are in the bank and the two tables
in fetch slots 4 and 5. The light family of FOG_SHADERS is not written: the capture has it from the light
table.

A list is refused (ValueError naming the shader) rather than read loosely: a hash is 16 hex digits (written
in upper case), never zero, listed once whatever its letters' case; the interpolator is an integer 0 to 15;
the form is "plain" or "alpha"; a shader of FOG_NOT_OF_THE_FORM (the lake, which fetches both tables with
other arithmetic) or the sky's is not a fogged shader; an empty list is no table.

usage: gen_fog_table.py --out src/native/capture/fog_shader_table.inc
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import light_formulas as lf  # noqa: E402

FORMS = {"plain": 0, "alpha": 1}
_HASH = re.compile(r"[0-9A-Fa-f]{16}")


def generate(shaders, not_of_the_form=()):
    """The table text for a list of light_formulas.FogShader (hash, family, world, form)."""
    shaders = list(shaders)
    if not shaders:
        raise ValueError("no fogged shader: the table is not generated from an empty list")
    excluded = {int(h, 16) for h in not_of_the_form}
    sky = int(lf.SKY_SHADER, 16)
    seen, lines = set(), []
    for s in shaders:
        if not isinstance(s.hash, str) or not _HASH.fullmatch(s.hash):
            raise ValueError(f"{s.hash!r}: a hash is 16 hex digits")
        value = int(s.hash, 16)
        if value == 0:
            raise ValueError(f"{s.hash}: the hash is zero")
        if value in seen:
            raise ValueError(f"{s.hash}: the shader is listed twice")
        seen.add(value)
        if value in excluded:
            raise ValueError(f"{s.hash}: the shader is not of the form (FOG_NOT_OF_THE_FORM)")
        if value == sky:
            raise ValueError(f"{s.hash}: the sky's shader has no fog block")
        if not isinstance(s.world, int) or isinstance(s.world, bool) or not 0 <= s.world <= 15:
            raise ValueError(f"{s.hash}: world {s.world!r} is not an interpolator 0 to 15")
        if not isinstance(s.form, str) or s.form not in FORMS:
            raise ValueError(f"{s.hash}: form {s.form!r} is not plain or alpha")
        lines.append((value, f"FABLE2_FOG_SHADER(0x{value:016X}ull, {s.world}, {FORMS[s.form]})"))
    lines.sort()
    return "\n".join(["// Generated by tools/xdk_sigmatch/gen_fog_table.py - do not edit."] + [line for _, line in lines]) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    Path(a.out).write_text(generate(lf.FOG_SHADERS, not_of_the_form=lf.FOG_NOT_OF_THE_FORM))


if __name__ == "__main__":
    main()
