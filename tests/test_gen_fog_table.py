"""Tests for tools/xdk_sigmatch/gen_fog_table.py (light_formulas.FOG_SHADERS -> fog_shader_table.inc; fog
sub-project, plan Task 3)."""
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "xdk_sigmatch"))

import gen_fog_table as gft  # noqa: E402
import light_formulas as lf  # noqa: E402

INC = ROOT / "src" / "native" / "capture" / "fog_shader_table.inc"

A, B, C = "00000000000000A1", "00000000000000B2", "00000000000000c3"


def shader(hash_, world=2, form="plain", family=None):
    return lf.FogShader(hash_, family, world, form)


class Generate(unittest.TestCase):
    def test_lines(self):
        out = gft.generate([shader(B, world=4), shader(C, form="alpha"), shader(A, world=0, family="object")]).splitlines()
        self.assertEqual(out[0], "// Generated by tools/xdk_sigmatch/gen_fog_table.py - do not edit.")
        # Sorted by hash, written in upper case; the interpolator of the world position; 1 for the blended
        # form. The light family is not the table's.
        self.assertEqual(out[1:], [
            "FABLE2_FOG_SHADER(0x00000000000000A1ull, 0, 0)",
            "FABLE2_FOG_SHADER(0x00000000000000B2ull, 4, 0)",
            "FABLE2_FOG_SHADER(0x00000000000000C3ull, 2, 1)",
        ])

    def test_refusals_name_the_shader(self):
        cases = [
            ([shader("A1")], "16 hex"),
            ([shader("0x000000000000A1")], "16 hex"),
            ([shader("000000000000000G")], "16 hex"),
            ([shader("0" * 16)], "zero"),
            ([shader(A), shader(A.lower())], "twice"),
            ([shader(A, world=16)], "interpolator"),
            ([shader(A, world=-1)], "interpolator"),
            ([shader(A, world=True)], "interpolator"),
            ([shader(A, world=2.0)], "interpolator"),
            ([shader(A, form="blend")], "form"),
            ([shader(A, form=None)], "form"),
        ]
        for shaders, word in cases:
            with self.subTest(word=word, shaders=shaders):
                with self.assertRaises(ValueError) as e:
                    gft.generate(shaders)
                self.assertIn(word, str(e.exception))
        with self.assertRaises(ValueError) as e:
            gft.generate([shader(A), shader(B, world=99)])
        self.assertIn(B, str(e.exception))

    def test_a_shader_that_is_not_of_the_form_or_is_the_sky_is_refused(self):
        with self.assertRaises(ValueError) as e:
            gft.generate([shader(A)], not_of_the_form=(A.lower(),))
        self.assertIn("not of the form", str(e.exception))
        with self.assertRaises(ValueError) as e:
            gft.generate([shader(lf.SKY_SHADER)])
        self.assertIn("sky", str(e.exception))

    def test_an_empty_list_is_refused(self):
        with self.assertRaises(ValueError):
            gft.generate([])


class Committed(unittest.TestCase):
    def test_the_committed_table_is_the_formulas_list(self):
        self.assertEqual(gft.generate(lf.FOG_SHADERS, not_of_the_form=lf.FOG_NOT_OF_THE_FORM), INC.read_text())
        text = INC.read_text()
        self.assertEqual(text.count("FABLE2_FOG_SHADER("), 40)
        # The water that is each captured frame's first fogged draw; a far-terrain, a terrain-layer and a
        # blended character's shader with their interpolators and forms.
        self.assertIn("FABLE2_FOG_SHADER(0xF6D98C7B4D98438Bull, 0, 0)", text)
        self.assertIn("FABLE2_FOG_SHADER(0x7DDAD5C29B3F56EEull, 1, 0)", text)
        self.assertIn("FABLE2_FOG_SHADER(0x9C2144E42E95A76Full, 4, 0)", text)
        self.assertIn("FABLE2_FOG_SHADER(0x401A01FD4E5F8757ull, 2, 1)", text)
        self.assertEqual(text.count(", 1)"), 10)
        # Not in it: the lake, the sky, and the tree pixel shaders (their fog is the vertex shader's).
        for absent in ("2B091BD0C45A7454", lf.SKY_SHADER, "7CD5", "00E0"):
            self.assertNotIn("0x" + absent, text)

    def test_main_writes_the_file(self):
        with tempfile.TemporaryDirectory() as d:
            out = Path(d) / "t.inc"
            gft.main(["--out", str(out)])
            self.assertEqual(out.read_text(), INC.read_text())


if __name__ == "__main__":
    unittest.main()
