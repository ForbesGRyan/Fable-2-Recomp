class CommittedTable(unittest.TestCase):
    def test_it_generates_the_committed_inc(self):
        data = gct.load(TABLE)
        self.assertEqual(gct.generate(data, vs_table=gtt.load(VS_TABLE)), INC.read_text())
        self.assertEqual(INC.read_text().count("FABLE2_SHADOW_CASTER("), len(CAPTURED_PAIRS))

    def test_the_pairs_are_the_captured_ones(self):
        data = gct.load(TABLE)
        self.assertEqual({(e["vs"], e["ps"]): e["kind"] for e in data}, CAPTURED_PAIRS)
        by_ps = {e["ps"]: e["alpha"] for e in data if e["kind"] == "alpha-test"}
        self.assertEqual(by_ps, {"0xF1EB2497108F159D": {"texture_slot": 0, "scale_register": "c15.w"},
                                 "0x33477588A5C01C7C": {"texture_slot": 0, "scale_register": None},
                                 "0x85A9A5EC510A9700": {"texture_slot": 0, "scale_register": None}})
        # What the table does not draw is said in the entry: the dissolve of the bushes, the sway of the
        # three deformed vertex shaders, the leaves' alpha-to-mask.
        limits = {e["vs"]: e.get("limitation", "") for e in data}
        self.assertIn("dissolve", limits["0xA8A5B2A89F70336A"])
        for vs in ("0xA8A5B2A89F70336A", "0xFBD39C64463E180B", "0x432563420047C96C"):
            self.assertIn("sway", limits[vs])
            self.assertTrue(gtt.load(VS_TABLE)[vs]["deformed"])
        self.assertIn("alpha-to-mask", limits["0x432563420047C96C"])

    def test_the_two_vertex_shaders_without_an_entry_have_one(self):
        table = gtt.load(VS_TABLE)
        for vs in ("0xA8A5B2A89F70336A", "0x87E0DB8B7C32F6A5"):
            self.assertEqual((table[vs]["base"], table[vs]["layout"]), (0, "dot"))
        self.assertEqual(table["0xA8A5B2A89F70336A"]["instance"]["mesh_fetch"], 3)
        self.assertEqual(table["0x87E0DB8B7C32F6A5"]["skin"]["index_component"], "z")

    @unittest.skipUnless(DUMPS.is_dir(), NO_DUMPS)
    def test_the_alpha_recipes_are_the_dumps(self):
        """shader_trace's reading of the three caster pixel shaders: the alpha is the w of tf0, times c15.w
        in the leaves' shader; the bushes' is multiplied by a computed term (the dissolve), which the trace
        refuses. All three read the texture at interpolator 0 times c8.xy plus c8.zw."""
        want = {"0xF1EB2497108F159D": ["c15.w"], "0x33477588A5C01C7C": []}
        for e in gct.load(TABLE):
            if e["kind"] != "alpha-test":
                continue
            ins = st.parse((DUMPS / f"shader_{e['ps'][2:]}.ucode.frag").read_text(errors="replace"))
            alpha = st.trace_ps_alpha(ins)
            if e["ps"] in want:
                self.assertEqual(alpha, {"source": "fetch", "slot": e["alpha"]["texture_slot"], "component": "w",
                                         "scale": want[e["ps"]]})
                self.assertEqual([e["alpha"]["scale_register"]] if e["alpha"]["scale_register"] else [], want[e["ps"]])
                fetch = next(t for t in st.texture_fetches(ins) if t.slot == 0)
                self.assertEqual(st.trace_ps_albedo(ins, fetch),
                                 {"u": {"input": "r0.x", "stages": [{"scale": "c8.x", "offset": "c8.z"}]},
                                  "v": {"input": "r0.y", "stages": [{"scale": "c8.y", "offset": "c8.w"}]}})
            else:
                self.assertIsInstance(alpha, st.Unsupported)
                self.assertIn("computed term", alpha.reason)
            self.assertEqual(st.find_kills(ins), [])
            self.assertEqual(sorted(t.slot for t in st.texture_fetches(ins))[0], 0)


@unittest.skipUnless(DUMPS.is_dir(), NO_DUMPS)
class CasterVertexShaders(unittest.TestCase):
    """vs_check.py --casters: a table entry replayed by position_check.py's functions on random streams
    against the shader's microcode."""
    TRIALS = 12

    def entry(self, hash_):
        return copy.deepcopy(gtt.load(VS_TABLE)["0x" + hash_])

    def test_every_caster_entry_agrees_with_its_microcode(self):
        lines, bad = vs_check.run_casters(trials=self.TRIALS)
        self.assertEqual(bad, 0, lines)
        self.assertEqual(len(lines), 8)
        n = 12 * self.TRIALS
        for line in lines:
            self.assertIn(f": {n} of {n} random vertices agree with the table entry", line)
        # Every vertex shader of the caster table is run, but the trunks' (deformed, no uv: nothing to compare).
        casters = {e["vs"][2:] for e in gct.load(TABLE)}
        self.assertEqual(casters - set(vs_check.CASTER_LITERALS), {"FBD39C64463E180B"})
        self.assertEqual(set(vs_check.CASTER_LITERALS) - casters, set())

    def test_the_instanced_entry_is_cut_as_the_microcode_cuts(self):
        agree, n, cut = vs_check.caster_check("A8A5B2A89F70336A", trials=self.TRIALS)
        self.assertEqual(agree, n)
        self.assertGreater(cut, n // 8)                 # both sides of the cut are reached
        self.assertGreater(n - cut, n // 8)
        # With the sway's amplitudes left on, the microcode moves the kept vertices: what "deformed" drops.
        agree, n, cut = vs_check.caster_check("A8A5B2A89F70336A", trials=self.TRIALS, sway=True)
        # (Not all of them: the sway is scaled by the vertex's height, and half of the random heights are
        # below the foot, where it is zero.)
        self.assertLess(agree, n - (n - cut) // 8)

    def wrong(self, hash_, change):
        entry = self.entry(hash_)
        change(entry)
        try:
            agree, n, _ = vs_check.caster_check(hash_, entry, trials=self.TRIALS)
        except Exception as e:      # an entry that does not match the fetches is refused by the replay
            return type(e).__name__
        return None if agree == n else f"{agree} of {n}"

    def test_wrong_entries_fail(self):
        def swap_rows(e):
            key = "instance" if "instance" in e else "skin"
            e[key]["row_fetches"] = e[key]["row_fetches"][::-1]

        cases = [
            ("A8A5B2A89F70336A", "rows reversed", swap_rows),
            ("A8A5B2A89F70336A", "the mesh fetch one too far", lambda e: e["instance"].update(mesh_fetch=4)),
            ("A8A5B2A89F70336A", "a bias of a vertex and a half", lambda e: e["instance"].update(bias=1.5)),
            ("A8A5B2A89F70336A", "count and first exchanged", lambda e: e["instance"].update(count="c12.z", first="c12.y")),
            ("A8A5B2A89F70336A", "another offset", lambda e: e["instance"].update(offset="c9.xyz")),
            ("A8A5B2A89F70336A", "no cut", lambda e: e["instance"].pop("cut")),
            ("A8A5B2A89F70336A", "row swizzles as stored", lambda e: e["instance"].update(row_swizzles=["xyzw"] * 3)),
            ("A8A5B2A89F70336A", "position swizzle as stored", lambda e: e.update(pos_swizzle="xyz1")),
            ("A8A5B2A89F70336A", "v from the position element", lambda e: e["uv"]["o0.y"].update(fetch=3, offset=0)),
            ("A8A5B2A89F70336A", "u from another half", lambda e: e["uv"]["o0.x"].update(src="w")),
            ("87E0DB8B7C32F6A5", "rows reversed", swap_rows),
            ("87E0DB8B7C32F6A5", "the index's source component named", lambda e: e["skin"].update(index_component="x")),
            ("87E0DB8B7C32F6A5", "rows one fetch early", lambda e: e["skin"].update(row_fetches=[2, 3, 4])),
            ("87E0DB8B7C32F6A5", "row swizzles as stored", lambda e: e["skin"].update(row_swizzles=["xyzw"] * 3)),
            ("87E0DB8B7C32F6A5", "u and v exchanged", lambda e: (e["uv"]["o0.x"].update(src="x"), e["uv"]["o0.y"].update(src="y"))),
            ("57818A7FD1C4F026", "u and v exchanged", lambda e: (e["uv"]["o0.x"].update(src="x"), e["uv"]["o0.y"].update(src="y"))),
            ("57818A7FD1C4F026", "combine layout", lambda e: e.update(layout="combine")),
            ("57818A7FD1C4F026", "another base", lambda e: e.update(base=4)),
            ("3A0F9098B839DDBC", "uv from the weights' dword", lambda e: e["uv"]["o0.x"].update(offset=4)),
            ("3A0F9098B839DDBC", "uv of another fetch", lambda e: e["uv"]["o0.y"].update(fetch=2)),
            ("432563420047C96C", "u and v exchanged", lambda e: (e["uv"]["o0.x"].update(src="x"), e["uv"]["o0.y"].update(src="y"))),
        ]
        for hash_, name, change in cases:
            with self.subTest(shader=hash_, wrong=name):
                self.assertIsNotNone(self.wrong(hash_, change), f"{hash_} agrees with: {name}")

    def test_the_dump_fetches_are_the_capture_rows_form(self):
        # The fetches of 0x8123C16DBF583F92 as a capture row lists them (native_discovery_20261008_105659.jsonl,
        # an in-scene row: "i", "instr", "slot", "reg", "fmt", "off", "stride", "mini", "signed", "norm", "exp", "swz").
        # "instr" is left out: the row counts instructions from the first, the dump's numbers include the
        # control-flow words before them.
        row = [{"i": 0, "instr": 4, "slot": 94, "reg": 4, "fmt": 32, "off": 0, "stride": 7, "mini": False, "signed": True,
                "norm": False, "exp": 0, "swz": 1217},
               {"i": 1, "instr": 5, "slot": 94, "reg": 2, "fmt": 32, "off": 2, "stride": 7, "mini": True, "signed": True,
                "norm": False, "exp": 0, "swz": 153},
               {"i": 2, "instr": 6, "slot": 94, "reg": 5, "fmt": 32, "off": 4, "stride": 7, "mini": True, "signed": True,
                "norm": False, "exp": 0, "swz": 1665},
               {"i": 3, "instr": 7, "slot": 94, "reg": 7, "fmt": 6, "off": 6, "stride": 7, "mini": True, "signed": False,
                "norm": True, "exp": 0, "swz": 3594}]
        got = vs_check.dump_fetches((DUMPS / "shader_8123C16DBF583F92.ucode.vert").read_text(errors="replace"))
        self.assertEqual([{k: v for k, v in f.items() if k not in ("attrs", "instr")} for f in got[:4]],
                         [{k: v for k, v in f.items() if k != "instr"} for f in row])

    def test_command_line(self):
        import contextlib
        import io
        from unittest import mock
        out = io.StringIO()
        with mock.patch.object(vs_check, "run_casters", lambda: (["a line"], 0)), contextlib.redirect_stdout(out):
            self.assertEqual(vs_check.main(["--casters"]), 0)
        self.assertEqual(out.getvalue(), "a line\n")
        with mock.patch.object(vs_check, "run_casters", lambda: (["a line"], 1)), contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(vs_check.main(["--casters"]), 1)


