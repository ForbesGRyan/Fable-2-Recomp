INC = ROOT / "src" / "native" / "capture" / "shadow_caster_table.inc"

VS_A, VS_B, PS_A = "0x00000000000000A1", "0x00000000000000B2", "0x00000000000000C3"


def opaque(vs=VS_A, **extra):
    return dict({"vs": vs, "ps": None, "kind": "opaque", "evidence": "e"}, **extra)


def tested(vs=VS_B, ps=PS_A, slot=0, scale=None, **extra):
    return dict({"vs": vs, "ps": ps, "kind": "alpha-test", "alpha": {"texture_slot": slot, "scale_register": scale},
                 "evidence": "e"}, **extra)


def vs_entry(uv=True):
    e = {"base": 0, "layout": "dot", "manual": True, "evidence": "e"}
    if uv:
        e["uv"] = {"o0.x": {"fetch": 1, "src": "y", "format": 31, "offset": 3, "stages": []},
                   "o0.y": {"fetch": 1, "src": "x", "format": 31, "offset": 3, "stages": []}}
    return e


class Generate(unittest.TestCase):
    def test_lines(self):
        out = gct.generate([tested(scale="c15.w"), opaque(), tested(vs=VS_A, slot=3)]).splitlines()
        self.assertEqual(out[0], "// Generated by tools/xdk_sigmatch/gen_caster_table.py - do not edit.")
        # Sorted by vertex shader, then pixel shader (none first). Kind 0 opaque, 1 alpha-test; an opaque
        # caster has slot -1; the scale is register * 4 + component (c15.w = 63), -1 without one.
        self.assertEqual(out[1:], [
            "FABLE2_SHADOW_CASTER(0x00000000000000A1ull, 0x0000000000000000ull, 0, -1, -1)",
            "FABLE2_SHADOW_CASTER(0x00000000000000A1ull, 0x00000000000000C3ull, 1, 3, -1)",
            "FABLE2_SHADOW_CASTER(0x00000000000000B2ull, 0x00000000000000C3ull, 1, 0, 63)",
        ])
        self.assertTrue(gct.generate([]).endswith("do not edit.\n"))

    def test_hashes_are_written_in_upper_case(self):
        out = gct.generate([tested(vs="0x00000000000000ab", ps="0x00000000000000cd")])
        self.assertIn("FABLE2_SHADOW_CASTER(0x00000000000000ABull, 0x00000000000000CDull, 1, 0, -1)", out)

    def test_an_opaque_caster_may_have_a_pixel_shader(self):
        out = gct.generate([opaque(ps=PS_A)])
        self.assertIn("FABLE2_SHADOW_CASTER(0x00000000000000A1ull, 0x00000000000000C3ull, 0, -1, -1)", out)

    def test_a_limitation_is_text_only(self):
        self.assertEqual(gct.generate([opaque(limitation="the sway is not drawn")]), gct.generate([opaque()]))

    def refused(self, data, pattern, **kw):
        with self.assertRaisesRegex(ValueError, pattern):
            gct.generate(data, **kw)

    def test_refuses_a_table_that_is_not_a_list_of_objects(self):
        self.refused({"0x1": opaque()}, "not a list")
        self.refused([["vs", VS_A]], "entry 0 is not an object")
        self.refused([opaque(), "x"], "entry 1 is not an object")

    def test_refuses_an_unknown_or_missing_key_with_the_hash(self):
        self.refused([opaque(alpah={})], f"{VS_A}: unknown key alpah")
        self.refused([opaque(kind="opaque", manual=True)], f"{VS_A}: unknown key manual")
        self.refused([tested(alpha={"texture_slot": 0, "scale_register": None, "component": "w"})],
                     f"{VS_B} with {PS_A}: unknown alpha key component")
        for key in ("ps", "kind", "evidence"):
            e = opaque()
            del e[key]
            self.refused([e], f"{VS_A}.*{key}")
        e = opaque()
        del e["vs"]
        self.refused([e], "entry 0.*vs")

    def test_refuses_missing_evidence_with_the_hash(self):
        for bad in ("", "   ", None, 3, ["e"]):
            self.refused([opaque(evidence=bad)], f"{VS_A}: no evidence")
            self.refused([tested(evidence=bad)], f"{VS_B} with {PS_A}: no evidence")
        self.refused([opaque(limitation="")], f"{VS_A}: limitation")
        self.refused([opaque(limitation=3)], f"{VS_A}: limitation")

    def test_refuses_bad_hashes(self):
        for bad in ("0x1", "00000000000000A1", "0x00000000000000G1", 0xA1, None, "0x00000000000000A1 "):
            self.refused([opaque(vs=bad)], "vs .* is not 0x and 16 hex digits")
        for bad in ("0x1", "none", 0, "0x00000000000000G1"):
            self.refused([opaque(ps=bad)], f"{VS_A}: ps .* is not null or 0x and 16 hex digits")
        self.refused([opaque(ps="0x0000000000000000")], f"{VS_A}: ps .*null")
        self.refused([opaque(vs="0x0000000000000000")], "vs .*zero")

    def test_refuses_an_unknown_kind(self):
        for bad in ("alpha", "Opaque", "", None, 1):
            self.refused([opaque(kind=bad)], f"{VS_A}: kind .* is not opaque or alpha-test")

    def test_refuses_an_alpha_entry_without_a_pixel_shader(self):
        self.refused([tested(ps=None)], f"{VS_B}: an alpha-test caster needs a pixel shader")

    def test_refuses_an_alpha_entry_without_its_recipe_and_an_opaque_one_with(self):
        e = tested()
        del e["alpha"]
        self.refused([e], f"{VS_B} with {PS_A}: an alpha-test caster needs alpha")
        self.refused([tested(alpha=None)], f"{VS_B} with {PS_A}: alpha is not an object")
        self.refused([tested(alpha={"texture_slot": 0})], f"{VS_B} with {PS_A}: alpha lacks scale_register")
        self.refused([tested(alpha={"scale_register": None})], f"{VS_B} with {PS_A}: alpha lacks texture_slot")
        self.refused([opaque(alpha={"texture_slot": 0, "scale_register": None})], f"{VS_A}: an opaque caster takes no alpha")

    def test_refuses_loose_slots_and_scale_registers(self):
        for bad in (-1, 32, 2.0, "0", True, None):
            self.refused([tested(slot=bad)], f"{VS_B} with {PS_A}: texture_slot .* is not an integer from 0 to 31")
        for bad in ("c256.w", "r1.x", "c15", "c15.xy", "-c15.w", 63, ["c15.w"], ""):
            self.refused([tested(scale=bad)], f"{VS_B} with {PS_A}: scale_register .* is not null or a pixel constant")

    def test_refuses_a_pair_listed_twice(self):
        self.refused([opaque(), opaque()], f"{VS_A}: the pair is listed twice")
        self.refused([tested(), tested(vs=VS_B.lower().replace("0X", "0x"), ps=PS_A.replace("C3", "c3"))],
                     "the pair is listed twice")
        gct.generate([opaque(), opaque(ps=PS_A)])                  # one vertex shader with two pixel shaders is two pairs

    def test_held_against_the_vertex_table(self):
        vs_table = {VS_A: vs_entry(uv=False), VS_B: vs_entry()}
        gct.generate([opaque(), tested()], vs_table=vs_table)
        self.refused([opaque(), tested()], f"{VS_B} with {PS_A}: the vertex shader has no entry",
                     vs_table={VS_A: vs_entry()})
        self.refused([opaque()], f"{VS_A}: the vertex shader's entry has no transform", vs_table={VS_A: {"manual": True}})
        self.refused([opaque()], f"{VS_A}: the vertex shader's entry has no transform",
                     vs_table={VS_A: dict(vs_entry(), base2=4)})
        # An alpha-tested caster's pixel shader reads the texture at interpolator 0: the vertex entry must
        # say where both of its coordinates come from.
        self.refused([tested()], f"{VS_B} with {PS_A}: the vertex shader's entry has no uv for o0.x and o0.y",
                     vs_table={VS_B: vs_entry(uv=False)})
        half = vs_entry()
        del half["uv"]["o0.y"]
        self.refused([tested()], "no uv for o0.x and o0.y", vs_table={VS_B: half})
        # The vertex table's keys match whatever their letters' case.
        gct.generate([tested(vs="0x00000000000000b2")], vs_table={VS_B: vs_entry()})

    def test_load_refuses_a_key_written_twice(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "casters.json"
            path.write_text('[{"vs": "%s", "ps": null, "kind": "opaque", "kind": "alpha-test", "evidence": "e"}]' % VS_A)
            with self.assertRaisesRegex(ValueError, "kind: the key is written twice"):
                gct.load(path)
            path.write_text(json.dumps([opaque()]))
            self.assertEqual(gct.load(path), [opaque()])

    def test_main_writes_the_table_and_reads_the_vertex_table_beside_it(self):
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            (d / "shadow-casters.json").write_text(json.dumps([opaque(), tested()]))
            out = d / "table.inc"
            # No vertex table beside it and none named: refused, not generated unchecked.
            with self.assertRaisesRegex(ValueError, "vertex table"):
                gct.main(["--json", str(d / "shadow-casters.json"), "--out", str(out)])
            self.assertFalse(out.exists())
            (d / "vs-transforms.json").write_text(json.dumps({VS_A: vs_entry(), VS_B: vs_entry(uv=False)}))
            with self.assertRaisesRegex(ValueError, "no uv"):
                gct.main(["--json", str(d / "shadow-casters.json"), "--out", str(out)])
            self.assertFalse(out.exists())
            (d / "other.json").write_text(json.dumps({VS_A: vs_entry(), VS_B: vs_entry()}))
            gct.main(["--json", str(d / "shadow-casters.json"), "--out", str(out), "--vs-json", str(d / "other.json")])
            self.assertEqual(out.read_text().count("FABLE2_SHADOW_CASTER("), 2)


