"""tools/xdk_sigmatch/gen_impostor_table.py (distant trees, plan Task 6): the far woods' impostor table as X-macro
lines, what it refuses, and that the committed src/native/capture/impostor_table.inc is the generator's output."""
import copy
import re
import struct
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "xdk_sigmatch"))

import gen_impostor_table as gen  # noqa: E402
import light_formulas as lf  # noqa: E402

INC = ROOT / "src" / "native" / "capture" / "impostor_table.inc"


def bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def made():
    """A small entry: two vertex registers, one pixel register, one literal register a bank."""
    return {"vs": "00000000000000AB", "ps": "00000000000000CD", "reg": (46, 8), "ps_reg": (12,),
            "vs_lit": {255: (0.0, 1.0, -1.0, 4.0)}, "ps_lit": {255: (0.0, 1.0, 0.1, 0.5)},
            "word_source": (1, 0, 3, 2), "word_endian": 2,
            "bounds": {("vs", 8): [(-1.0, 1.0)] * 4, ("vs", 46): [(-2.0, 2.0)] * 4, ("ps", 12): [(0.0, 4096.0)] * 4},
            "size_max": 64.0, "b129": 2}


class Generate(unittest.TestCase):
    def test_every_line_of_a_made_entry(self):
        text = gen.generate(made())
        lines = text.splitlines()
        self.assertTrue(lines[0].startswith("// Generated by tools/xdk_sigmatch/gen_impostor_table.py"))
        body = [line for line in lines if not line.startswith("//")]
        self.assertEqual(body[0], "FABLE2_IMPOSTOR_SHADERS(0x00000000000000ABull, 0x00000000000000CDull)")
        self.assertEqual([line for line in body if line.startswith("FABLE2_IMPOSTOR_VS_REGISTER")],
                         ["FABLE2_IMPOSTOR_VS_REGISTER(8)", "FABLE2_IMPOSTOR_VS_REGISTER(46)"])           # ascending
        self.assertEqual([line for line in body if line.startswith("FABLE2_IMPOSTOR_PS_REGISTER")], ["FABLE2_IMPOSTOR_PS_REGISTER(12)"])
        self.assertIn("FABLE2_IMPOSTOR_LITERAL(0, 255, 0x00000000u, 0x3F800000u, 0xBF800000u, 0x40800000u)", body)
        self.assertIn("FABLE2_IMPOSTOR_LITERAL(1, 255, 0x00000000u, 0x3F800000u, 0x%08Xu, 0x3F000000u)" % bits(0.1), body)
        self.assertEqual([line for line in body if line.startswith("FABLE2_IMPOSTOR_WORD")],
                         ["FABLE2_IMPOSTOR_WORD(0, 1)", "FABLE2_IMPOSTOR_WORD(1, 0)", "FABLE2_IMPOSTOR_WORD(2, 3)", "FABLE2_IMPOSTOR_WORD(3, 2)"])
        self.assertEqual(body.count("FABLE2_IMPOSTOR_ENDIAN(2)"), 1)
        self.assertIn("FABLE2_IMPOSTOR_BOUND(0, 8, 0, 0xBF800000u, 0x3F800000u)", body)
        self.assertIn("FABLE2_IMPOSTOR_BOUND(1, 12, 3, 0x00000000u, 0x45800000u)", body)
        self.assertEqual(sum(line.startswith("FABLE2_IMPOSTOR_BOUND") for line in body), 12)            # four a register
        self.assertEqual(body.count("FABLE2_IMPOSTOR_SIZE_MAX(0x42800000u)"), 1)
        self.assertEqual(body[-1], "FABLE2_IMPOSTOR_B129(0x00000002u)")
        kinds = [re.match(r"FABLE2_IMPOSTOR_([A-Z0-9_]+)\(", line).group(1) for line in body]
        self.assertEqual(sorted(set(kinds)), sorted(["SHADERS", "VS_REGISTER", "PS_REGISTER", "LITERAL", "WORD", "ENDIAN", "BOUND", "SIZE_MAX", "B129"]))
        self.assertTrue(text.endswith("\n") and "\r" not in text)

    def refused(self, change, word):
        entry = copy.deepcopy(made())
        change(entry)
        with self.assertRaises(ValueError) as e:
            gen.generate(entry)
        self.assertIn(word, str(e.exception))

    def test_what_is_refused(self):
        self.refused(lambda e: e["bounds"].__setitem__(("vs", 8), [(1.0, -1.0)] * 4), "above its high")
        self.refused(lambda e: e.__setitem__("reg", (8, 46, 8)), "twice")
        self.refused(lambda e: e.__setitem__("ps_reg", (12, 12)), "twice")
        self.refused(lambda e: e.__setitem__("word_source", (1, 0, 4, 2)), "0 to 3")
        self.refused(lambda e: e.__setitem__("word_source", (1, 0, 0, 2)), "once")
        self.refused(lambda e: e.__setitem__("word_endian", 4), "endian")
        self.refused(lambda e: e.__setitem__("reg", (8, 250)), "below 248")
        self.refused(lambda e: e["bounds"].pop(("vs", 46)), "no bound")
        self.refused(lambda e: e["bounds"].__setitem__(("vs", 46), [(-2.0, 2.0)] * 3), "four")
        self.refused(lambda e: e["bounds"].__setitem__(("vs", 46), [(-2.0, float("nan"))] * 4), "no number")
        self.refused(lambda e: e["bounds"].__setitem__(("vs", 99), [(-2.0, 2.0)] * 4), "not a register of the table")
        self.refused(lambda e: e.__setitem__("vs", "12"), "16 hex digits")
        self.refused(lambda e: e.__setitem__("ps", "0" * 16), "zero")
        self.refused(lambda e: e.__setitem__("size_max", 0.0), "size")
        self.refused(lambda e: e.__setitem__("b129", 3), "one bit")
        self.refused(lambda e: e.__setitem__("vs_lit", {255: (0.0, 1.0)}), "four values")

    def test_the_committed_file_is_the_generators(self):
        entry = gen.entry()
        self.assertEqual(INC.read_text(encoding="utf-8").replace("\r\n", "\n"), gen.generate(entry))
        self.assertEqual(gen.main(["--check"]), 0)

    def test_the_real_entry_is_the_formulas_table(self):
        e = gen.entry()
        s = lf.IMPOSTOR_SHADER
        self.assertEqual((e["vs"], e["ps"], tuple(e["reg"]), tuple(e["ps_reg"])), (s["vs"], s["ps"], tuple(s["reg"]), tuple(s["ps_reg"])))
        self.assertEqual((tuple(e["word_source"]), e["word_endian"], e["b129"]), ((1, 0, 3, 2), 2, lf.IMPOSTOR_B129))
        self.assertEqual(set(e["bounds"]), {("vs", r) for r in s["reg"]} | {("ps", r) for r in s["ps_reg"]})
        # the spec's own bounds stand where it gives them
        self.assertEqual(e["bounds"][("ps", 29)][1], (gen.ABOVE_ZERO, 4.0))
        self.assertEqual(e["bounds"][("ps", 29)][0], (0.0, 4096.0))
        self.assertEqual(e["bounds"][("ps", 12)][1], (0.0, 4096.0))
        self.assertEqual(e["bounds"][("ps", 12)][3], (0.0, 4.0))
        self.assertEqual(e["bounds"][("ps", 31)][0], (gen.ABOVE_ZERO, 64.0))
        self.assertEqual(e["bounds"][("ps", 20)][3], (gen.ABOVE_ZERO, 64.0))
        self.assertEqual(e["bounds"][("vs", 72)][0], (-1e7, 1e7))
        self.assertEqual(e["bounds"][("vs", 47)][0], (-1e6, 1e6))
        # and every captured value lies inside its bound (the five discovery captures' spans, t6_bounds.txt)
        for key, span in gen.CAPTURED.items():
            for (lo, hi), (blo, bhi) in zip(span, e["bounds"][key]):
                self.assertTrue(blo <= lo <= hi <= bhi, (key, lo, hi, blo, bhi))
        self.assertTrue(gen.CAPTURED_SIZE[1] < e["size_max"] <= 4.0 * gen.CAPTURED_SIZE[1])

    def test_check_names_a_stale_file(self):
        import tempfile
        with tempfile.TemporaryDirectory() as folder:
            out = Path(folder) / "impostor_table.inc"
            self.assertEqual(gen.main(["--out", str(out)]), 0)
            self.assertEqual(gen.main(["--check", "--out", str(out)]), 0)
            out.write_text(out.read_text().replace("FABLE2_IMPOSTOR_ENDIAN(2)", "FABLE2_IMPOSTOR_ENDIAN(1)"), newline="\n")
            self.assertEqual(gen.main(["--check", "--out", str(out)]), 1)


if __name__ == "__main__":
    unittest.main()
